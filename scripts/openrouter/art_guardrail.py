#!/usr/bin/env python3
"""Post-generation guardrail for the AI hero art.

`flux`-style image models intermittently bake garbled text into the artwork, or
resolve a style like De Stijl into a realistic image framed inside a graphic
border (a collage). More generally, the provider can return a clean photograph
even when the prompt requires a drawn illustration in a selected visual style.
This module runs a single vision check on the generated bytes and returns a
verdict so the caller can regenerate before the bad frame reaches the wall.
Broad text rejection can be disabled independently of collage, requested-
treatment and palette checks; a narrow creator-signature/watermark/logo check
remains active.

It fails OPEN: any error inspecting the image returns ok=True, so the guardrail
can never block a board from rendering.
"""
import base64
import json
import urllib.request

from scripts.common import get_openrouter_api_key
from scripts.openrouter.network import urlopen_with_context


INSPECT_PROMPT = (
    "You are a QA check for a four-ink weather illustration. "
    "Answer ONLY about the artwork itself. Detailed illustrated backgrounds, "
    "drawn atmospheric depth and unified paper-cut forms are valid illustration "
    "treatments and are not themselves collage. Return STRICT JSON, no markdown:\n"
    '{"has_text": <true if ANY letters, words, numbers, or garbled/fake '
    'lettering appear anywhere in the image>, '
    '"has_watermark_or_signature": <true if an artist signature, handwritten '
    "signature-like mark, watermark, or prominent creator/brand logo appears; "
    'ordinary environmental signage does not count>, '
    '"is_collage": <true if it is a collage, or a realistic/photographic image '
    "placed inside a graphic frame, border, grid, or block (two competing "
    'aesthetics in one image)>, '
    '"note": "<= 12 word reason>"}'
)

COLLAGE_ONLY_PROMPT = (
    "Check whether this artwork mixes competing visual aesthetics. "
    "Detailed illustrated backgrounds, drawn atmospheric depth and unified "
    "paper-cut forms are valid illustration treatments and are not themselves "
    "collage. "
    "Ordinary environmental lettering, street or shop signs, labels, numbers, "
    "and incidental background logos are allowed and must not by themselves "
    "affect is_collage. "
    "Separately inspect the image, especially its corners and edges, for "
    "creator marks: set has_watermark_or_signature true for an artist "
    "signature, handwritten signature-like mark, watermark, or prominent "
    "creator/brand logo. A tiny incidental label or natural scene sign does "
    "not count. Do not reject on broad text alone. "
    "Return STRICT JSON, no markdown:\n"
    '{"has_watermark_or_signature": <true if a creator signature, watermark, '
    'or prominent creator/brand logo appears, otherwise false>, '
    '"is_collage": <true if it is a collage, or a realistic/photographic image '
    "placed inside a graphic frame, border, grid, or block (two competing "
    'aesthetics in one image)>, "note": "<= 12 word reason>"}'
)


def _request_prompt(check_text, expected_treatment):
    """Build the vision request, adding the selected-treatment contract.

    The prompt used for normal guardrail checks predates style/medium matching.
    When the caller supplies the selected style's compact expected-treatment
    description, append an explicit form check to the same request. This keeps
    the guardrail at one vision call while making a plain photograph rejectable
    even when it has no competing collage frame and no creator mark.
    """
    prompt = INSPECT_PROMPT if check_text else COLLAGE_ONLY_PROMPT
    if not expected_treatment:
        return prompt
    return (
        prompt
        + "\n\nRequested treatment: "
        + expected_treatment
        + "\nJudge the image's medium and visual form, not only its subject. Set "
        '"matches_requested_treatment" to true only when the whole image is a '
        "drawn illustration that clearly uses the requested visual treatment. "
        "Set it to false for a plain photograph, photographic realism, camera "
        "depth of field, or any realistic image whose medium or form does not "
        "match the requested illustration style, even when the scene is "
        "cohesive, a natural environment has incidental signage, and no creator "
        "mark is present. Do not insert photographs or accept photographic "
        "realism as an illustration. "
        'The final JSON must also include "matches_requested_treatment" as a '
        "boolean."
    )


def _guardrail_model(settings):
    openrouter = settings.get("openrouter", {})
    return (
        settings.get("pipeline", {}).get("image_guardrail_model")
        or openrouter.get("image_tool_model")
        or openrouter.get("text_model")
    )


def inspect_art(image_bytes, settings, expected_treatment=None):
    """Return the normalized guardrail verdict for one vision request.

    ``expected_treatment`` is the compact style/form contract for the selected
    art treatment (for example, a Bauhaus illustration). When supplied, the same
    vision request also returns ``matches_requested_treatment``. A false verdict
    rejects the candidate; a missing boolean is recorded as ``unverified`` so an
    omitted style judgement cannot masquerade as an auditable acceptance.

    The result includes ``ok``, ``status``, ``has_text``, ``text_check_enabled``,
    ``has_watermark_or_signature``, ``is_collage``, ``matches_requested_treatment``,
    ``expected_treatment`` and ``note``. Broad ``has_text`` is ``None`` when that
    classifier is disabled; the narrow creator-mark check stays active. A
    completed relaxed-mode verdict is only ``accepted`` when the model explicitly
    reported no watermark or signature and, when requested, matched the expected
    treatment.

    ``status`` separates the three outcomes the caller must treat differently:

    * ``accepted``   -- the enabled vision checks ran and passed;
    * ``rejected``   -- the vision check ran and flagged the image;
    * ``unverified`` -- the check could not run or returned an incomplete
      verdict (no model/key, timeout, network error, missing required field).
      The legacy ``ok=True`` fail-open behaviour is preserved so the guardrail
      never blocks a render, but the caller records it as unverified rather
      than accepted.
    """
    pipeline = settings.get("pipeline", {})
    check_text = pipeline.get("image_guardrail_check_text", True)
    if isinstance(expected_treatment, str):
        expected_treatment = expected_treatment.strip() or None
    else:
        expected_treatment = None
    model = _guardrail_model(settings)
    api_key = get_openrouter_api_key(settings)
    if not model or not api_key:
        return {
            "ok": True,
            "status": "unverified",
            "skipped": "no model or key",
            "expected_treatment": expected_treatment,
            "matches_requested_treatment": None,
        }

    timeout = pipeline.get("image_guardrail_timeout_seconds", 30)
    url = settings["openrouter"]["base_url"].rstrip("/") + "/chat/completions"
    img_b64 = base64.b64encode(image_bytes).decode("ascii")
    body = {
        "model": model,
        "messages": [
            {
                "role": "user",
                "content": [
                    {"type": "text", "text": _request_prompt(check_text, expected_treatment)},
                    {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{img_b64}"}},
                ],
            }
        ],
        "response_format": {"type": "json_object"},
    }
    # GPT-6 reasoning requests do not support temperature. Preserve the
    # existing deterministic setting for other providers/models.
    if not model.startswith(("openai/gpt-6", "gpt-6")):
        body["temperature"] = 0
    request = urllib.request.Request(
        url=url,
        data=json.dumps(body).encode("utf-8"),
        method="POST",
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
    )
    try:
        with urlopen_with_context(request, timeout=timeout, settings=settings) as resp:
            payload = json.loads(resp.read().decode("utf-8"))
        content = payload["choices"][0]["message"]["content"].strip()
        if content.startswith("```"):
            content = content.split("```", 2)[1].lstrip("json").strip()
        verdict = json.loads(content)
    except Exception as error:  # noqa: BLE001 - guardrail must fail open
        return {
            "ok": True,
            "status": "unverified",
            "error": str(error),
            "expected_treatment": expected_treatment,
            "matches_requested_treatment": None,
        }

    # Ignore unsolicited broad text flags when that classifier is disabled.
    # None records that broad text was not checked, rather than claiming it is
    # absent. The narrow creator-mark verdict remains active in both modes.
    has_text = bool(verdict.get("has_text")) if check_text else None
    mark_value = verdict.get("has_watermark_or_signature")
    has_watermark_or_signature = mark_value if isinstance(mark_value, bool) else None
    is_collage = bool(verdict.get("is_collage"))
    match_value = verdict.get("matches_requested_treatment")
    matches_requested_treatment = match_value if isinstance(match_value, bool) else None
    rejected = (
        bool(has_text)
        or has_watermark_or_signature is True
        or is_collage
        or (bool(expected_treatment) and matches_requested_treatment is False)
    )
    normalized = {
        "ok": not rejected,
        "status": "rejected" if rejected else "accepted",
        "has_text": has_text,
        "text_check_enabled": bool(check_text),
        "has_watermark_or_signature": has_watermark_or_signature,
        "is_collage": is_collage,
        "matches_requested_treatment": matches_requested_treatment,
        "expected_treatment": expected_treatment,
        "note": verdict.get("note", ""),
    }
    if rejected:
        return normalized
    if has_watermark_or_signature is None and not check_text:
        # In relaxed mode the prompt requires this field. Its absence means the
        # narrow check did not produce an auditable pass, so fail open as
        # unverified instead of recording a misleading ``accepted`` verdict.
        # Strict mode retains its prior acceptance semantics when an older
        # response omits the extra, narrower field.
        normalized.update({
            "ok": True,
            "status": "unverified",
            "error": "vision verdict missing has_watermark_or_signature",
        })
        return normalized
    if expected_treatment and matches_requested_treatment is None:
        # The caller asked a direct style/medium question. An omitted answer is
        # not an auditable match, so keep the image fail-open but unverified.
        normalized.update({
            "ok": True,
            "status": "unverified",
            "error": "vision verdict missing matches_requested_treatment",
        })
        return normalized
    return normalized
